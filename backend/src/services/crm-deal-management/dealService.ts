    /**
     * Get deals by pipeline stage (for Kanban board)
     */
    async getDealsByStage(
        organizationId: string,
        pipelineId: string,
        agentId?: string
    ): Promise<Record<string, Deal[]>> {
        try {
            const params: any[] = [organizationId, pipelineId];
            let agentClause = '';
            if (agentId) {
                agentClause = ` AND d.assigned_agent = $3`;
                params.push(agentId);
            }
            const result = await db.query<Deal & { stage_name: string; stage_order: number }>(
                `SELECT 
          d.*,
          ds.stage_name,
          ds.stage_order,
          ds.stage_color,
          c.first_name || ' ' || c.last_name as primary_contact_name,
          (SELECT ARRAY_AGG(title) FROM crm_properties WHERE id = ANY(d.property_ids)) as property_names,
          (SELECT EXISTS(SELECT 1 FROM valuations v WHERE v.property_id = ANY(d.property_ids) AND v.status = 'completed')) as has_valuation
         FROM deals d
         JOIN deal_stages ds ON d.stage_id = ds.id
         LEFT JOIN contacts c ON d.primary_contact_id = c.id
         WHERE d.organization_id = $1 
           AND d.pipeline_id = $2 
           AND d.deleted_at IS NULL
           AND d.deal_status = 'active'${agentClause}
         ORDER BY ds.stage_order, d.created_at DESC`,
                params
            );

            // Group by stage
            const dealsByStage: Record<string, Deal[]> = {};
            for (const deal of result.rows) {
                const stageId = deal.stage_id;
                if (!dealsByStage[stageId]) {
                    dealsByStage[stageId] = [];
                }
                dealsByStage[stageId].push(deal);
            }

            return dealsByStage;
        } catch (error) {
            logger.error('Error fetching deals by stage', { error, organizationId, pipelineId });
            throw error;
        }
    }

    /**
     * Get deal metrics
     */
    async getDealMetrics(organizationId: string): Promise<{
        total_active: number;
        total_value: number;
        total_weighted_value: number;
        won_deals: number;
        lost_deals: number;
        avg_close_probability: number;
        by_stage: Record<string, { count: number; total_value: number }>;
    }> {
        try {
            const result = await db.query(
                `SELECT 
          COUNT(*) FILTER (WHERE deal_status = 'active') as total_active,
          COUNT(*) FILTER (WHERE deal_status = 'won') as won_deals,
          COUNT(*) FILTER (WHERE deal_status = 'lost') as lost_deals,
          COALESCE(SUM(deal_value) FILTER (WHERE deal_status = 'active'), 0) as total_value,
          COALESCE(SUM(weighted_value) FILTER (WHERE deal_status = 'active'), 0) as total_weighted_value,
          AVG(close_probability) FILTER (WHERE deal_status = 'active') as avg_close_probability
         FROM deals
         WHERE organization_id = $1 AND deleted_at IS NULL`,
                [organizationId]
            );

            const metrics = result.rows[0];

            // Get by stage
            const stageResult = await db.query(
                `SELECT 
          ds.stage_name,
          COUNT(d.id) as count,
          COALESCE(SUM(d.deal_value), 0) as total_value
         FROM deal_stages ds
         LEFT JOIN deals d ON ds.id = d.stage_id AND d.deal_status = 'active' AND d.deleted_at IS NULL
         JOIN deal_pipelines dp ON ds.pipeline_id = dp.id
         WHERE dp.organization_id = $1
         GROUP BY ds.stage_name`,
                [organizationId]
            );

            const byStage: Record<string, { count: number; total_value: number }> = {};
            for (const row of stageResult.rows) {
                byStage[row.stage_name] = {
                    count: parseInt(row.count, 10),
                    total_value: parseFloat(row.total_value),
                };
            }

            return {
                total_active: parseInt(metrics.total_active, 10),
                total_value: parseFloat(metrics.total_value),
                total_weighted_value: parseFloat(metrics.total_weighted_value),
                won_deals: parseInt(metrics.won_deals, 10),
                lost_deals: parseInt(metrics.lost_deals, 10),
                avg_close_probability: parseFloat(metrics.avg_close_probability) || 50,
                by_stage: byStage,
            };
        } catch (error) {
            logger.error('Error fetching deal metrics', { error, organizationId });
            throw error;
        }
    }

